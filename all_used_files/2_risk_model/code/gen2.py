def gx(s, f):
    rep = {'{a}': 'а' if f else '', '{la}': 'ла' if f else '', '{as}': 'ась' if f else 'ся', '{oy}': 'ой' if f else 'им',
           '{aya}': 'ая' if f else 'ый', '{na}': 'на' if f else 'ен', '{ka}': 'ца' if f else 'к', '{yo}': 'ла' if f else 'ёл',
           '{im}': 'ней' if f else 'ним', '{ya}': 'я' if f else 'й', '{oi}': 'ой' if f else 'ым', '{ii}': 'ая' if f else 'ий'}
    for k, v in rep.items(): s = s.replace(k, v)
    return s

def alt(s):
    while True:
        m = re.search(r'\[([^\[\]]*)\]', s)
        if not m: return re.sub(r'\s+', ' ', s).strip()
        s = s[:m.start()] + R.choice(m.group(1).split('|')) + s[m.end():]

